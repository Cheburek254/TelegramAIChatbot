def styled_text(text):
    if text == START_TEXT:
        for source, target in START_VARIANTS:
            text = text.replace(source, target, 1)
        return text
    first, newline, rest = text.partition("\n")
    if first in HEADINGS:
        return HEADINGS[first] + newline + rest
    if first.startswith("📌 Задачи и дедлайны · "):
        return (
            HEADINGS["📌 Задачи и дедлайны"] + first[len("📌 Задачи и дедлайны") :] + newline + rest
        )
    for prefix, target in PREFIXES.items():
        if first.startswith(prefix):
            return target + text[len(prefix) :]
    if first == "<b>⚙️ Настройки</b>":
        return "<b>⚙️ Шо настраиваем?</b>" + newline + rest
    return text


class SystemSpeechMiddleware:
    def __init__(self, store):
        self.store = store

    async def __call__(self, make_request, bot, method):
        if not isinstance(method, (SendMessage, EditMessageText, EditMessageReplyMarkup)):
            return await make_request(bot, method)
        owner = method.chat_id
        if type(owner) is not int or owner <= 0:
            return await make_request(bot, method)
        changes = {}
        markup = method.reply_markup
        if isinstance(markup, InlineKeyboardMarkup):
            rows = [
                [
                    button.model_copy(update={"text": BUTTONS[button.text]})
                    if button.text in BUTTONS
                    else button
                    for button in row
                ]
                for row in markup.inline_keyboard
            ]
            if rows != markup.inline_keyboard:
                changes["reply_markup"] = markup.model_copy(update={"inline_keyboard": rows})
        if isinstance(method, (SendMessage, EditMessageText)) and not method.entities:
            styled = styled_text(method.text)
            if styled != method.text and len(styled.encode("utf-16-le")) // 2 <= 4096:
                changes["text"] = styled
        if changes:
            try:
                async with asyncio.timeout(1):
                    style = await self.store.current(owner)
            except (asyncpg.PostgresError, OSError, TimeoutError):
                style = None
            if style == "yiddish":
                method = method.model_copy(update=changes)
        return await make_request(bot, method)
